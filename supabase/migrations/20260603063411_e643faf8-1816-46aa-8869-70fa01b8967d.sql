Forex is the global market where currencies are exchanged. Every trade compares one currency against another, which is why instruments are quoted as pairs such as EURUSD, GBPJPY, or XAUUSD. The first currency is the base currency and the second is the quote currency. If EURUSD rises, the euro is gaining value against the U.S. dollar. If EURUSD falls, the euro is weakening against the dollar.

