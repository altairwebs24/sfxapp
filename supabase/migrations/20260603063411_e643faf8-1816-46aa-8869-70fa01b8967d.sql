Margin lets you control a position larger than the cash you put aside for the trade. Leverage is powerful because it magnifies gains and losses. It is not free money. It is borrowed exposure, and poor control of leverage is one of the fastest ways to destroy an account.

## Lot sizes
Forex position size is usually described in lots. A standard lot is 100,000 units of the base currency. A mini lot is 10,000 units. A micro lot is 1,000 units. Smaller accounts should usually start with micro lots because they allow tighter control of risk.

## Margin requirement
If your broker offers 1:100 leverage, a position worth 10,000 units may require roughly 100 units of margin. That does not mean the trade only risks 100. The full position still moves with the market, and losses can grow quickly if the stop loss is too large or if multiple trades stack in the same direction.

## Free margin and margin level
Free margin is the available cushion left after open trades use margin. Margin level compares equity to used margin. If losses reduce equity too much, the broker can issue a margin call or close positions automatically. This usually happens when traders open positions that are too large for their account.

## Risk before lot size
The correct way to choose lot size starts with risk, not excitement. Decide how much of the account you are willing to lose if the stop loss is hit. Many disciplined traders risk a small fixed percentage per trade, such as 0.5% to 2%. Then they calculate position size based on the distance to the stop loss.

## Example thinking process
- Account size: R5,000.
- Risk per trade: 1%, or R50.
- Stop loss distance: 25 pips.
- Position size must be small enough that 25 pips equals about R50.

## Practical takeaway
Leverage should make position sizing flexible, not reckless. If a normal stop loss would lose too much money, reduce the lot size or skip the trade.$$),

